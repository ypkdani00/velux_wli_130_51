struct CmdGuard {
  CmdGuard()  { if (cmdLock) xSemaphoreTakeRecursive(cmdLock, portMAX_DELAY); }
  ~CmdGuard() { if (cmdLock) xSemaphoreGiveRecursive(cmdLock); }
};
struct LogGuard {
  LogGuard()  { if (logLock) xSemaphoreTake(logLock, portMAX_DELAY); }
  ~LogGuard() { if (logLock) xSemaphoreGive(logLock); }
};

