// ===========================================================================
//  VELUX WLI 130 51  -  ESP32-C6 IR remote control, Zigbee + Wi-Fi
// ===========================================================================
//  The WLI 130 51 is the VELUX wall keypad with a built-in IR receiver
//  (WLC 100 control unit). It is normally operated with the WLR 100 remote.
//  This firmware generates the same commands, checksum included - see
//  VeluxIR.h for the protocol details.
//
//  Each keypad is identified, over IR, ONLY by its security code (the 10
//  internal DIP switches). The 0-F rotary address selector is NOT part of the
//  IR frame: it is only used on the wire towards the WLC 100. So a single
//  board can drive several keypads, as long as they are all in view of the IR
//  LED: each one only reacts to frames carrying its own code.
//
//  Board: DFRobot FireBeetle 2 ESP32-C6
//    GPIO22 -> Gravity IR transmitter module (DFR0095)
//    GPIO21 -> Gravity self-locking switch (DFR0423): ON = Wi-Fi on
//    GPIO0  -> battery voltage (the board's own 1:2 divider)
//    GPIO15 -> onboard LED: steady = booting, flash every 1 s = Zigbee pairing,
//              every 5 s = joined and waiting
//    GPIO9  -> BOOT button: hold 3s to leave the Zigbee network
//  Zigbee runs all the time (window coverings for Home Assistant); Wi-Fi
//  (web UI, HTTP API, OTA) only while the switch is ON. See Config.h §7.
//
//  Build with PlatformIO (platformio.ini): it sets up Zigbee end-device mode,
//  the partition table and light sleep. export_release.ps1 does it in one step.
//
//  ---------------------------------------------------------------------
//  ADAPTING THIS FIRMWARE TO A DIFFERENT INSTALLATION
//  Everything you are likely to need to change lives in Config.h: the
//  security code of each keypad, the Wi-Fi credentials, the pins, the
//  safety delay, the power-saving options and Zigbee. This file should not
//  need any editing.
//  ---------------------------------------------------------------------
// ===========================================================================

