// ------------------------------ power management ----------------------------
//
// See kEnablePowerManagement in Config.h.
static String   pmStatus     = "off";
static bool     usbLog       = true;   // USB console on this boot, see "USB log" in the web UI
// Mode of this boot, from the mode switch: Wi-Fi on (web UI, HTTP API, OTA)
// or Zigbee only. Read first thing in setup(): it sets the CPU clock.
static bool     wifiEnabled  = true;
static esp_pm_lock_handle_t pmBusyLock = nullptr;   // nullptr = no PM running

// Holds the CPU at full clock and out of light sleep for as long as it
// exists. Used around IR transmission (a nap between the two copies of a
// frame would stretch the gap) and ADC readings. A no-op when PM isn't
// running.
struct PmBusy {
  PmBusy()  { if (pmBusyLock) esp_pm_lock_acquire(pmBusyLock); }
  ~PmBusy() { if (pmBusyLock) esp_pm_lock_release(pmBusyLock); }
};

static void setupPowerManagement() {
  if (!kEnablePowerManagement) {
    pmStatus = "off (kEnablePowerManagement = false)";
    return;
  }
  if (usbLog) {   // light sleep switches the chip's USB port off
    pmStatus = "off (USB log on)";
    return;
  }
  // Wi-Fi on: fixed at the maximum. Zigbee only: floats from the lowest clock
  // (the crystal, 40MHz) at rest up to kCpuFreqMhz while there is work -
  // a Zigbee packet, an IR frame (PmBusy) - and goes back down by itself.
  esp_pm_config_t cfg = {};
  cfg.max_freq_mhz = wifiEnabled ? kCpuFreqWifiMhz : kCpuFreqMhz;
  cfg.min_freq_mhz = wifiEnabled ? kCpuFreqWifiMhz : kCpuFreqIdleMinMhz;
  cfg.light_sleep_enable = true;
  const String range = (cfg.min_freq_mhz == cfg.max_freq_mhz)
                           ? String(cfg.max_freq_mhz) + " MHz"
                           : String(cfg.min_freq_mhz) + "-" + cfg.max_freq_mhz + " MHz";
  esp_err_t err = esp_pm_configure(&cfg);
  if (err == ESP_OK) {
    pmStatus = String("light sleep + DFS ") + range;
  } else if (err == ESP_ERR_NOT_SUPPORTED) {
    // Either no PM at all in this build, or PM without tickless idle (no
    // light sleep). Frequency scaling alone is still worth having.
    cfg.light_sleep_enable = false;
    err = esp_pm_configure(&cfg);
    if (err == ESP_OK) pmStatus = String("DFS only ") + range + " (no tickless idle in this core build)";
  }
  if (err != ESP_OK) {
    pmStatus = (err == ESP_ERR_NOT_SUPPORTED)
                   ? "not in this core build (CONFIG_PM_ENABLE off)"
                   : String("esp_pm_configure failed: ") + esp_err_to_name(err);
    return;
  }
  esp_pm_lock_create(ESP_PM_CPU_FREQ_MAX, 0, "velux", &pmBusyLock);
}

// Firmware uploads (web UI or OTA) move a megabyte
// through a radio that normally naps between beacons: keep everything awake
// for the duration, or the transfer crawls and can time out. Released again
// only if the update fails - on success the board reboots anyway.
static bool pmUpdateHold = false;
static void holdAwakeForUpdate(bool hold) {
  if (hold == pmUpdateHold) return;
  pmUpdateHold = hold;
  WiFi.setSleep(hold ? WIFI_PS_NONE : kWifiPowerSave);
  if (pmBusyLock) {
    if (hold) esp_pm_lock_acquire(pmBusyLock);
    else      esp_pm_lock_release(pmBusyLock);
  }
}

