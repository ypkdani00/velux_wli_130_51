// How long after an open or close the actuators of keypad p may still be
// travelling: the full travel time of that kind of motor plus a margin.
static uint32_t travelWindowMs(int p) {
  return (kPanels[p].kind == kCoverBlind ? kTravelTimeBlindMs : kTravelTimeWindowMs) + kTravelMarginMs;
}

// ------------------------------ position estimate ---------------------------
//
// The IR protocol never reports back, so the position is worked out from the
// travel time: an actuator moves at a constant speed, so in
// kTravelTime*Ms it covers 100%. An open or close starts it moving, a STOP
// (or a reversal's STOP) freezes it, and reaching an end stops the estimate
// there - which also corrects any drift, since after a full run the position
// is known again. Home Assistant gets the estimate over Zigbee (see
// handlePositions); at boot the position is unknown (kZigbeeStartLiftPct).
// Raw frames sent by hand (/api/sendhex) are not tracked.
struct MotorPos {
  float    pct;    // Zigbee lift percentage: 0 = fully open, 100 = fully closed
  int8_t   dir;    // -1 opening, +1 closing, 0 standing still
  uint32_t since;  // millis() of pct
};
static MotorPos motorPos[kPanelCount][3];
static portMUX_TYPE posMux = portMUX_INITIALIZER_UNLOCKED;

static float fullTravelMs(int p) {   // the travel time without the safety margin
  return (float)(kPanels[p].kind == kCoverBlind ? kTravelTimeBlindMs : kTravelTimeWindowMs);
}

// Brings the estimate of one motor up to now. Call with posMux held.
static void posAdvance(int p, int i, uint32_t now) {
  MotorPos& s = motorPos[p][i];
  if (s.dir) {
    s.pct += s.dir * (float)(uint32_t)(now - s.since) * 100.0f / fullTravelMs(p);
    if (s.pct <= 0)   { s.pct = 0;   s.dir = 0; }
    if (s.pct >= 100) { s.pct = 100; s.dir = 0; }
  }
  s.since = now;
}

// A frame has gone out: the addressed motors start moving (open / close) or
// stand still (STOP). m = motor 0..2, 3 = all three.
static void posCommand(int p, int m, int a) {
  const uint32_t now = millis();
  portENTER_CRITICAL(&posMux);
  for (int i = (m == 3 ? 0 : m); i <= (m == 3 ? 2 : m); ++i) {
    posAdvance(p, i, now);
    motorPos[p][i].dir = (a == 0) ? -1 : (a == 2) ? +1 : 0;
  }
  portEXIT_CRITICAL(&posMux);
}

// One open/stop/close command, anti-jam logic included - shared by the HTTP
// API and Zigbee. p = panel, m = motor 0..2 or 3 = all three, a: 0 = open,
// 1 = stop, 2 = close (index into kActions[]). Returns nullptr on success,
// otherwise what was wrong. *autoStop tells whether a STOP had to go first.
static const char* runCommand(int p, int m, int a, bool* autoStop) {
  if (p < 0 || p >= kPanelCount) return "invalid panel";
  if (m < 0 || m > 3 || a < 0 || a > 2) return "invalid motor or action";
  if (panelCode[p] == 0xFFFF) return "invalid security code in Config.h";

  // A STOP announces itself before taking the lock: a command in progress
  // (it holds the lock, in its pause) sees it and gives way at once.
  if (a == 1) stopPendingCover = p * 4 + m;
  CmdGuard guard;

  bool autoStopSent = false;

  // A STOP for this motor is already on its way: this command is obsolete.
  if (a != 1 && stopCovers(stopPendingCover, p, m)) return "cancelled: a STOP followed";

  if (a == 1) {                              // STOP: always allowed, clears the cooldown
    if (m == 3) {
      for (uint8_t i = 0; i < 4; ++i) lastDirAction[p][i] = -1;
    } else {
      lastDirAction[p][m] = -1;
    }
  } else {                                   // open (0) or close (2)
    const uint32_t now = millis();
    const uint32_t travelMs = travelWindowMs(p);

    // Check if any addressed motor is currently moving in the opposite direction
    bool needAutoStop = false;
    if (m == 3) {
      for (uint8_t i = 0; i < 4; ++i) {
        if (lastDirAction[p][i] >= 0 && lastDirAction[p][i] != a &&
            (uint32_t)(now - lastDirTime[p][i]) < travelMs) {
          needAutoStop = true;
          break;
        }
      }
    } else {
      if ((lastDirAction[p][m] >= 0 && lastDirAction[p][m] != a &&
           (uint32_t)(now - lastDirTime[p][m]) < travelMs) ||
          (lastDirAction[p][3] >= 0 && lastDirAction[p][3] != a &&
           (uint32_t)(now - lastDirTime[p][3]) < travelMs)) {
        needAutoStop = true;
      }
    }

    if (needAutoStop) {
      // Actuator is actively travelling in reverse: send STOP first to prevent WLC 100 fault/lockout
      sendFrame(velux::build(velux::ACT_STOP, kMotors[m], panelCode[p]));
      posCommand(p, m, 1);   // the motor stands still during the pause
      autoStopSent = true;
      // Pause for the motor to settle - cut short, and the new direction
      // dropped, if a STOP for it arrives meanwhile.
      for (uint32_t t = 0; t < kAutoStopPauseMs; t += 10) {
        if (stopCovers(stopPendingCover, p, m)) return "cancelled: a STOP followed";
        delay(10);
      }
    }

    const uint32_t sendTime = millis();
    if (m == 3) {
      for (uint8_t i = 0; i < 4; ++i) {
        lastDirAction[p][i] = a;
        lastDirTime[p][i] = sendTime;
      }
    } else {
      lastDirAction[p][m] = a;
      lastDirTime[p][m] = sendTime;
    }
  }

  sendFrame(velux::build(kActions[a], kMotors[m], panelCode[p]));
  posCommand(p, m, a);   // position estimate: the motors now move / stand still
  if (a == 1 && stopPendingCover == p * 4 + m) stopPendingCover = -1;   // the STOP has gone out
  if (autoStop) *autoStop = autoStopSent;
  return nullptr;
}

static void handleSend() {
  const int p = server.arg("panel").toInt();
  const int m = server.arg("motor").toInt();
  const int a = server.arg("action").toInt();
  bool autoStop = false;
  const char* err = runCommand(p, m, a, &autoStop);
  if (err) { fail(err); return; }
  sendJson(autoStop ? "{\"ok\":true,\"autoStop\":true}" : "{\"ok\":true}");
}

static void handleSendHex() {
  String v = server.arg("v");
  v.trim();
  uint32_t frame = 0;
  if (v.length() == 24 && v.indexOf('x') < 0) {
    for (uint8_t i = 0; i < 24; ++i) frame = (frame << 1) | (v[i] == '1' ? 1 : 0);
  } else {
    frame = (uint32_t)strtoul(v.c_str(), nullptr, 0) & 0xFFFFFF;
  }
  if (!frame) { fail("invalid frame"); return; }
  sendFrame(frame);
  sendJson("{\"ok\":true}");
}

// The week of battery readings kept in flash, oldest first:
// [{"t":unix|0,"up":s,"mv":mV,"pct":%,"boot":bool}, ...]
static void handleBatteryHistory() {
  String j = "[";
  prefs.begin("bathist", true);
  const uint8_t head = prefs.getUChar("head", 0) % kBatteryHistoryLen;
  bool first = true;
  for (uint8_t k = 0; k < kBatteryHistoryLen; ++k) {
    char key[8];
    batteryHistoryKey((head + k) % kBatteryHistoryLen, key, sizeof(key));
    BatteryRecord r;
    if (!prefs.isKey(key) || prefs.getBytes(key, &r, sizeof(r)) != sizeof(r)) continue;
    if (!first) j += ',';
    first = false;
    j += "{\"t\":";
    j += r.time;
    j += ",\"up\":";
    j += r.uptime;
    j += ",\"mv\":";
    j += r.mv;
    j += ",\"pct\":";
    j += r.pct;
    j += ",\"boot\":";
    j += (r.flags & kBatRecBoot) ? "true" : "false";
    j += '}';
  }
  prefs.end();
  j += ']';
  sendJson(j);
}

