// Anti-reversal cooldown bookkeeping: last non-stop action and its timestamp,
// per panel/motor combination. kMotors has 4 entries (3 motors + "all"), so 4
// slots per panel are enough: commands on a single motor and on "all" are
// tracked separately.
// Zigbee commands are executed by their own task (zbCmdTask) at a higher
// priority than loop() and the web server, so neither makes a command wait.
