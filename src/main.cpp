static void pushLog(const String& line) {
  LogGuard guard;
  if (logCount == kLogEntries) {   // full: the oldest entry makes room
    for (uint8_t i = 0; i < kLogEntries - 1; ++i) {
      logLines[i] = logLines[i + 1];
      logTimes[i] = logTimes[i + 1];
    }
    logCount = kLogEntries - 1;
  }
  logLines[logCount] = line;
  logTimes[logCount] = clockStamp();
  Serial.print(logTimes[logCount]);
  Serial.print("  ");
  Serial.println(line);
  ++logCount;
}

static String describe(uint32_t f) {
  const velux::Frame r = velux::decode(f);
  String s = hex24(f);
  s += "  ";
  s += velux::actionName(r.action);
  s += " / ";
  s += velux::motorName(r.motor);
  s += " / set ";
  s += (r.set == 0) ? String("all") : String(r.set);
  s += " / sec ";
  s += bin(r.security, 10);
  const char* p = panelBySecurity(r.security);
  if (p) {
    s += " [";
    s += p;
    s += ']';
  }
  if (!velux::checksumOk(f)) s += "  (unexpected checksum!)";
  return s;
}

// ------------------------------ IR TX ---------------------------------------
//
// The RMT peripheral plays the frame in hardware, carrier included: one
// symbol per bit, mark (carrier on) then space, 1 tick = 1 us like the
// timings in VeluxIR.h. The channel only exists while a frame goes out: an
// enabled RMT channel holds a power-management lock that would keep the chip
// out of light sleep.
static const uint32_t kRmtTickHz  = 1000000;
static const uint32_t kRmtTimeout = 500;   // ms; a frame lasts ~40 ms
// Which signal level lights the LED (kIrActiveLow in Config.h): the Gravity
// DFR0095 module lights its LED when the signal is LOW, so there idle is
// HIGH and the marks (carrier) are LOW. A wrong setting leaves the LED
// permanently lit - the keypads then never see a pulse.
static const uint8_t kIrOn  = kIrActiveLow ? 0 : 1;
static const uint8_t kIrOff = kIrActiveLow ? 1 : 0;

static void irIdle() {
  pinMode(kIrTxPin, OUTPUT);
  digitalWrite(kIrTxPin, kIrOff);
}
// rmtSetCarrier()'s "carrier_level" argument ends up in the driver's
// polarity_active_low flag, i.e. inverted: it must be true when the marks
// are LOW (carrier applied while the level is low), false when they are HIGH.

// Web UI "IR LED test": the carrier runs continuously, to check the LED and
// its aim with a phone camera (an IR LED shows up as a bright violet-white
// dot). It switches itself off after kIrTestMaxMs - the LED draws tens of mA.
static const uint32_t kIrTestMaxMs = 10000;
static bool     irTestOn    = false;
static uint32_t irTestUntil = 0;

static void irTestSet(bool on) {
  if (on == irTestOn) {
    if (on) irTestUntil = millis() + kIrTestMaxMs;   // pressed again: restart the clock
    return;
  }
  if (on) {
    static rmt_data_t sym[1];                       // must outlive the transmission
    sym[0].level0 = kIrOn;  sym[0].duration0 = 32767;   // carrier on, both halves
    sym[0].level1 = kIrOn;  sym[0].duration1 = 32767;
    if (!rmtInit(kIrTxPin, RMT_TX_MODE, RMT_MEM_NUM_BLOCKS_1, kRmtTickHz)) return;
    if (!rmtSetCarrier(kIrTxPin, true, kIrActiveLow, velux::kCarrierHz, 0.5f) ||
        !rmtWriteLooping(kIrTxPin, sym, 1)) {
      rmtDeinit(kIrTxPin);
      return;
    }
    irTestUntil = millis() + kIrTestMaxMs;
  } else {
    rmtDeinit(kIrTxPin);
    irIdle();   // IR LED off
  }
  irTestOn = on;
  pushLog(on ? "--  IR LED test on" : "--  IR LED test off");
}

static void irTestTimeout() {
  if (irTestOn && (int32_t)(millis() - irTestUntil) >= 0) irTestSet(false);
}

static void sendFrame(uint32_t frame) {
  CmdGuard guard;     // one frame at a time, whoever asks
  irTestSet(false);   // the test owns the RMT channel
  uint16_t raw[velux::kRawLen];
  velux::toRaw(frame, raw);
  rmt_data_t sym[velux::kBits];
  for (uint8_t i = 0; i < velux::kBits; ++i) {
    sym[i].level0 = kIrOn;   sym[i].duration0 = raw[2 * i];       // mark
    sym[i].level1 = kIrOff;  sym[i].duration1 = raw[2 * i + 1];   // space
  }

  PmBusy busy;   // full clock, no light sleep until done
  const uint32_t t0 = millis();
  uint32_t gapMs = 0;
  bool ok = rmtInit(kIrTxPin, RMT_TX_MODE, RMT_MEM_NUM_BLOCKS_1, kRmtTickHz);
  if (ok) {
    rmtSetEOT(kIrTxPin, kIrOff);   // the line rests "LED off" between and after frames
    ok = rmtSetCarrier(kIrTxPin, true, kIrActiveLow, velux::kCarrierHz, 0.5f) &&
         rmtWrite(kIrTxPin, sym, velux::kBits, kRmtTimeout);   // the WLR 100 sends the frame
    const uint32_t g0 = millis();
    delay(velux::kRepeatGapMs);                                 // twice in a row
    gapMs = millis() - g0;
    ok = ok && rmtWrite(kIrTxPin, sym, velux::kBits, kRmtTimeout);
    rmtDeinit(kIrTxPin);
  }
  // Timing check for the USB log: a frame is ~97 ms in all (2 x 39 + 19); a
  // longer gap between the copies means the CPU was busy elsewhere.
  Serial.printf("[%lu ms] IR frame: %lu ms in all, %lu ms between the two copies (nominal %u)\n",
                (unsigned long)millis(), (unsigned long)(millis() - t0), (unsigned long)gapMs,
                (unsigned)velux::kRepeatGapMs);
  irIdle();      // IR LED off until the next frame
  if (stopPendingCover < 0) delay(60);   // a gap before any next frame - but not before a STOP

  pushLog(String(ok ? "TX  " : "!!  IR transmit FAILED: ") + describe(frame));
}

// ------------------------------ battery -------------------------------------

// Typical resting discharge curve of a single Li-ion/LiPo cell: voltage (mV,
// strictly decreasing) -> state of charge (%). Interpolated linearly between
// points. The curve is flat in the middle, so a few mV of ADC error there is
// worth several percent - see kBatteryCalibration in Config.h.
struct SocPoint { uint16_t mv; uint8_t pct; };
static const SocPoint kLiIonCurve[] = {
  {4200, 100}, {4150, 95}, {4110, 90}, {4080, 85}, {4020, 80}, {3980, 75},
  {3950,  70}, {3910, 65}, {3870, 60}, {3850, 55}, {3840, 50}, {3820, 45},
  {3800,  40}, {3790, 35}, {3770, 30}, {3750, 25}, {3730, 20}, {3710, 15},
  {3690,  10}, {3610,  5}, {3270,  0},
};
static const uint32_t kBatterySampleMs = 60000;   // the cell changes over hours

static float batteryMv = -1;   // smoothed battery voltage; < 0 = no reading yet

static uint8_t batteryPercent(float mv) {
  const uint8_t n = sizeof(kLiIonCurve) / sizeof(kLiIonCurve[0]);
  if (mv >= kLiIonCurve[0].mv) return 100;
  if (mv <= kLiIonCurve[n - 1].mv) return 0;
  uint8_t i = 1;
  while (mv < kLiIonCurve[i].mv) ++i;
  const SocPoint& hi = kLiIonCurve[i - 1];
  const SocPoint& lo = kLiIonCurve[i];
  return lo.pct + (uint8_t)((mv - lo.mv) * (hi.pct - lo.pct) / (hi.mv - lo.mv) + 0.5f);
}

// One burst of 16 readings, averaged, then folded into an exponential moving
// average: the ADC is noisy on its own and Wi-Fi transmit bursts move
// the supply around on top of that, while the battery itself only changes
// over hours - so heavy smoothing costs nothing.
static void sampleBattery() {
  PmBusy busy;                                     // steady clocks while the ADC converts
  uint32_t mvSum = 0;
  for (uint8_t i = 0; i < 16; ++i) mvSum += analogReadMilliVolts(kBatteryPin);   // eFuse-calibrated
  const float mv = (mvSum / 16.0f) * (kBatteryRTopOhm + kBatteryRBottomOhm) /
                   kBatteryRBottomOhm * kBatteryCalibration;
  batteryMv = (batteryMv < 0) ? mv : batteryMv + 0.2f * (mv - batteryMv);
}

// A reading in the battery history (and a line on the USB log) every
// kBatteryLogMs, plus one at boot: a record of how fast the battery drains,
// e.g. after changing a power setting. Written from the loop's regular
// wake-up, never a wake of its own.
static const uint32_t kBatteryLogMs = 2UL * 60 * 60 * 1000;   // 2h
static uint32_t batteryLastLog = 0;

// The same readings, kept in flash (NVS, namespace "bathist") for a week so
// they survive restarts and a flat battery: one record per key, r0..r83 in a
// ring, "head" = next slot to overwrite. Each reading writes a few dozen
// bytes 12 times a day - negligible flash wear. Read by /api/battery/history.
struct BatteryRecord {
  uint32_t time;     // Unix time (UTC) from NTP; 0 = clock not set yet
  uint32_t uptime;   // seconds since that restart
  uint16_t mv;
  uint8_t  pct;
  uint8_t  flags;    // kBatRecBoot
};
static const uint8_t kBatteryHistoryLen = 84;   // 7 days x 12 readings
static const uint8_t kBatRecBoot = 2;           // first reading after a restart

static void batteryHistoryKey(uint8_t slot, char* key, size_t len) {
  snprintf(key, len, "r%u", (unsigned)slot);
}

static void storeBatteryRecord(const BatteryRecord& r) {
  prefs.begin("bathist", false);
  const uint8_t head = prefs.getUChar("head", 0) % kBatteryHistoryLen;
  char key[8];
  batteryHistoryKey(head, key, sizeof(key));
  prefs.putBytes(key, &r, sizeof(r));
  prefs.putUChar("head", (head + 1) % kBatteryHistoryLen);
  prefs.end();
}

static void logBattery(bool boot = false) {
  if (batteryMv < 0) return;

  BatteryRecord r;
  const time_t now = time(nullptr);
  r.time   = (now > 1700000000) ? (uint32_t)now : 0;   // before NTP the clock reads ~1970
  r.uptime = millis() / 1000;
  r.mv     = (uint16_t)(batteryMv + 0.5f);
  r.pct    = batteryPercent(batteryMv);
  r.flags  = boot ? kBatRecBoot : 0;
  storeBatteryRecord(r);

  String s = "BAT  up ";
  s += formatUptime(millis() / 1000);
  s += "  battery ";
  s += batteryPercent(batteryMv);
  s += "% (";
  s += String(batteryMv / 1000.0f, 2);
  s += " V)";
  // Not in the frame log (commands only): the readings are in the battery
  // history. The USB log gets the line.
  Serial.print(clockStamp());
  Serial.print("  ");
  Serial.println(s);
  batteryLastLog = millis();
}

static void handleBattery() {
  static uint32_t lastSample = 0;
  const uint32_t now = millis();
  if ((uint32_t)(now - lastSample) < kBatterySampleMs) return;
  lastSample = now;
  sampleBattery();
  if ((uint32_t)(now - batteryLastLog) >= kBatteryLogMs) logBattery();
}

