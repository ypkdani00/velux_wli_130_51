// FNV-1a over the page source, evaluated by the compiler ('\r' skipped so a
// CRLF checkout hashes the same). If WebUI.h was edited without regenerating
// WebUI_gz.h, the build stops here instead of serving the old page.
constexpr uint32_t webUiHash(const char* s, size_t n) {
  uint32_t h = 2166136261u;
  for (size_t i = 0; i < n; ++i) {
    if (s[i] == '\r') continue;
    h ^= (uint8_t)s[i];
    h *= 16777619u;
  }
  return h;
}
