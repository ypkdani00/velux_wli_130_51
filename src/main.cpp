// Scans for nearby Wi-Fi networks and returns them as a JSON array, sorted by
// signal strength (strongest first), de-duplicated by SSID and with hidden
// (blank-SSID) networks skipped since there is nothing to click on for those.
// This is a blocking call (a couple of seconds) - acceptable here since it
// only runs when the user presses "Scan networks" in the web UI. Requires
// the STA radio to be active, which is why setupWifi() below always enables
// it (WIFI_AP_STA / WIFI_STA), even while only running as a setup access
// point.
static void handleWifiScan() {
  const int n = WiFi.scanNetworks();

  // Sort indices by RSSI descending (simple insertion sort - n is always
  // small, a few dozen networks at most).
  static int order[64];
  const int count = (n < 0) ? 0 : (n > 64 ? 64 : n);
  for (int i = 0; i < count; ++i) order[i] = i;
  for (int i = 1; i < count; ++i) {
    const int key = order[i];
    const int keyRssi = WiFi.RSSI(key);
    int k = i - 1;
    while (k >= 0 && WiFi.RSSI(order[k]) < keyRssi) { order[k + 1] = order[k]; --k; }
    order[k + 1] = key;
  }

  static String seen[64];
  uint8_t seenCount = 0;
  String j = "[";
  bool first = true;
  for (int i = 0; i < count; ++i) {
    const int ni = order[i];
    const String ssid = WiFi.SSID(ni);
    if (!ssid.length()) continue;               // hidden network, nothing to select
    bool dup = false;
    for (uint8_t k = 0; k < seenCount; ++k)
      if (seen[k] == ssid) { dup = true; break; }
    if (dup) continue;
    if (seenCount < 64) seen[seenCount++] = ssid;

    if (!first) j += ',';
    first = false;
    j += "{\"ssid\":\"";
    j += jsonEscape(ssid);
    j += "\",\"rssi\":";
    j += WiFi.RSSI(ni);
    j += ",\"secure\":";
    j += (WiFi.encryptionType(ni) == WIFI_AUTH_OPEN) ? "false" : "true";
    j += "}";
  }
  j += "]";
  WiFi.scanDelete();
  sendJson(j);
}

static void handleWifi() {
  const String body = server.arg("plain");
  String ssid, pass;
  if (!jsonStringField(body, "ssid", ssid) || !jsonStringField(body, "pass", pass)) {
    fail("invalid json");
    return;
  }
  if (!ssid.length()) { fail("empty SSID"); return; }
  if (ssid.length() > 32) { fail("SSID too long (max 32 bytes)"); return; }
  // WPA2: 8-63 characters, or a 64-digit hex key. Empty = open network.
  if (pass.length() && (pass.length() < 8 || pass.length() > 64)) {
    fail("password must be 8-63 characters (or empty for an open network)");
    return;
  }

  prefs.begin("velux", false);
  prefs.putString("ssid", ssid);
  prefs.putString("pass", pass);
  prefs.end();

  sendJson("{\"ok\":true}");
  delay(300);
  restartBoard();
}

