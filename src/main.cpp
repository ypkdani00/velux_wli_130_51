// the whole point of this endpoint is to let you change it without
// reflashing, so once you have changed it here it should stick, not get
// silently overridden by whatever is still in Config.h.
static String currentApPassword() {
  prefs.begin("velux", true);
  const String p = prefs.getString("appass", "");
  prefs.end();
  return p.length() ? p : String(kApPassword);
}

static void handleApPassword() {
  const String body = server.arg("plain");
  String pass;
  if (!jsonStringField(body, "pass", pass)) { fail("invalid json"); return; }
  // WPA2-PSK requires 8-63 characters; empty is accepted here as "reset to
  // the Config.h default", not as "make the AP open" - open would be a
  // surprising, easy-to-trigger-by-accident outcome for a password field.
  if (pass.length() > 0 && pass.length() < 8) {
    fail("password must be at least 8 characters (or empty to reset to the default)");
    return;
  }
  if (pass.length() > 63) { fail("password too long (max 63 characters)"); return; }

  prefs.begin("velux", false);
  if (pass.length()) prefs.putString("appass", pass);
  else prefs.remove("appass");
  prefs.end();

  sendJson("{\"ok\":true}");
  delay(300);
  restartBoard();
}

