// ------------------------------ firmware update -----------------------------
//
// Flashes a new firmware .bin uploaded through the web UI, using the chip's
// own OTA machinery (the same one ArduinoOTA uses). Two things worth knowing:
//
//   - Wi-Fi credentials and every setting live in a separate NVS partition,
//     not in the application partition this overwrites - they survive an
//     update with no extra code needed to "preserve" them.
//   - There is no authentication on this (or any other) endpoint, matching
//     the rest of this project's LAN-only threat model. Anyone who can reach
//     this page on your network can flash arbitrary firmware onto the board.
//     If that's a concern on your network, don't expose this device beyond
//     your LAN (no port forwarding), same advice as for the rest of the API.
static bool updateFailed = false;

static void handleFirmwareUpload() {
  HTTPUpload& upload = server.upload();
  if (upload.status == UPLOAD_FILE_START) {
    updateFailed = false;
    pushLog(String("--  firmware update starting: ") + upload.filename);
    holdAwakeForUpdate(true);
    if (!Update.begin(UPDATE_SIZE_UNKNOWN)) {
      updateFailed = true;
      Update.printError(Serial);
    }
  } else if (upload.status == UPLOAD_FILE_WRITE && !updateFailed) {
    if (Update.write(upload.buf, upload.currentSize) != upload.currentSize) {
      updateFailed = true;
      Update.printError(Serial);
    }
  } else if (upload.status == UPLOAD_FILE_END && !updateFailed) {
    if (Update.end(true)) {
      pushLog(String("OK  firmware update complete: ") + upload.totalSize + " bytes, rebooting");
    } else {
      updateFailed = true;
      Update.printError(Serial);
    }
  } else if (upload.status == UPLOAD_FILE_ABORTED) {
    updateFailed = true;
    pushLog("--  firmware update aborted by the client");
    holdAwakeForUpdate(false);
  }
}

// Runs after handleFirmwareUpload() has streamed the whole file. Sends the
// final result, then reboots into the new firmware (or, on failure, back
// into this same one - the currently running app is only replaced once the
// new image is verified complete, so a failed/aborted upload leaves the
// board exactly as it was).
static void handleFirmwareResult() {
  if (updateFailed || Update.hasError()) {
    String msg = "update failed: ";
    msg += Update.errorString();
    pushLog(String("!!  ") + msg);
    fail(msg.c_str());
    holdAwakeForUpdate(false);
    return;
  }
  server.sendHeader("Connection", "close");
  sendJson("{\"ok\":true}");
  delay(1000);
  restartBoard();
}

