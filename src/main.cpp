// ------------------------------ Wi-Fi ---------------------------------------

static void startAp() {
  if (apActive) return;
  WiFi.mode(WIFI_AP_STA);
  WiFi.setTxPower(kWifiTxPower);
  if (kWifiNarrowBandwidth) {
    esp_wifi_set_bandwidth(WIFI_IF_AP, WIFI_BW_HT20);
    esp_wifi_set_bandwidth(WIFI_IF_STA, WIFI_BW_HT20);
  }
  const String apPass = currentApPassword();
  WiFi.softAP(kApSsid, apPass.c_str());
  apActive = true;
  Serial.printf("Access point \"%s\" -> http://%s\n", kApSsid,
                WiFi.softAPIP().toString().c_str());
}

static void stopAp() {
  if (!apActive) return;
  WiFi.softAPdisconnect(true);
  WiFi.mode(WIFI_STA);
  WiFi.setTxPower(kWifiTxPower);
  if (kWifiNarrowBandwidth) {
    esp_wifi_set_bandwidth(WIFI_IF_STA, WIFI_BW_HT20);
  }
  apActive = false;
  Serial.println("Access point off (connected to Wi-Fi).");
}

// WiFi.begin(ssid, pass) plus the listen interval (kWifiListenInterval),
// which the Arduino core doesn't expose and resets to the default on every
// begin(ssid, pass): set the credentials without connecting, patch the
// driver's station config, then connect with that stored config. The core's
// automatic reconnects and WiFi.reconnect() reuse it, so it sticks.
static void wifiBeginSta() {
  WiFi.begin(configuredSsid.c_str(), configuredPass.c_str(), 0, nullptr, false);
  wifi_config_t conf;
  if (esp_wifi_get_config(WIFI_IF_STA, &conf) == ESP_OK) {
    conf.sta.listen_interval = kWifiListenInterval;
    esp_wifi_set_config(WIFI_IF_STA, &conf);
  }
  WiFi.begin();
}

static void setupWifi() {
  // A hardcoded SSID (kWifiSsid, at the top of this file) always wins over
  // whatever was saved from the web UI. Otherwise fall back to the
  // credentials stored in flash (NVS) by a previous /api/wifi call.
  configuredSsid = kWifiSsid;
  configuredPass = kWifiPassword;
  if (!configuredSsid.length()) {
    prefs.begin("velux", true);
    configuredSsid = prefs.getString("ssid", "");
    configuredPass = prefs.getString("pass", "");
    prefs.end();
  }

  WiFi.setHostname(kHostname);
  // USB log of what the radio does, to find out why the board becomes
  // unreachable (disconnect reasons are the interesting part).
  WiFi.onEvent([](WiFiEvent_t ev, WiFiEventInfo_t info) {
    switch (ev) {
      case ARDUINO_EVENT_WIFI_STA_CONNECTED:       Serial.println("Wi-Fi event: STA connected"); break;
      case ARDUINO_EVENT_WIFI_STA_DISCONNECTED:
        Serial.printf("Wi-Fi event: STA disconnected, reason %u\n", info.wifi_sta_disconnected.reason); break;
      case ARDUINO_EVENT_WIFI_STA_GOT_IP:          Serial.printf("Wi-Fi event: got IP %s\n", WiFi.localIP().toString().c_str()); break;
      case ARDUINO_EVENT_WIFI_STA_LOST_IP:         Serial.println("Wi-Fi event: lost IP"); break;
      case ARDUINO_EVENT_WIFI_AP_STACONNECTED:     Serial.println("Wi-Fi event: a client joined the access point"); break;
      case ARDUINO_EVENT_WIFI_AP_STADISCONNECTED:
        Serial.printf("Wi-Fi event: a client left the access point, reason %u\n", info.wifi_ap_stadisconnected.reason); break;
      default: break;
    }
  });
  if (configuredSsid.length()) {
    WiFi.mode(WIFI_STA);
    WiFi.setTxPower(kWifiTxPower);   // must come after mode(): driver needs to be up
    if (kWifiNarrowBandwidth) esp_wifi_set_bandwidth(WIFI_IF_STA, WIFI_BW_HT20);
    wifiBeginSta();
    Serial.printf("Connecting to %s", configuredSsid.c_str());
    const uint32_t until = millis() + 15000;
    while (WiFi.status() != WL_CONNECTED && millis() < until) {
      delay(400);
      Serial.print('.');
    }
    Serial.println();
  }
  staConnected = (WiFi.status() == WL_CONNECTED);
  if (staConnected) {
    Serial.printf("Connected: http://%s  (or http://%s.local)\n",
                  WiFi.localIP().toString().c_str(), kHostname);
  }

  // The access point runs only while we're NOT connected to a home network:
  // the setup fallback - nothing to reach the board with otherwise.
  if (!staConnected) startAp();
  WiFi.setSleep(kWifiPowerSave);    // see the note in Config.h; ignored while the AP runs
  MDNS.begin(kHostname);
  MDNS.addService("http", "tcp", 80);
}

// Non-blocking Wi-Fi watchdog: monitors connection status and handles
// progressive recovery when the home network drops, without interrupting IR
// reception or the web server.
static void handleWifiWatchdog() {
  if (!configuredSsid.length()) return;

  const uint32_t now = millis();
  static uint32_t lastCheck = 0;
  if ((uint32_t)(now - lastCheck) < kWifiWatchdogIntervalMs) return;
  lastCheck = now;

  static uint32_t lostSince = 0;
  static uint32_t lastAttempt = 0;
  static bool wasConnected = staConnected;

  const bool isConnected = (WiFi.status() == WL_CONNECTED);

  if (isConnected) {
    if (!wasConnected) {
      staConnected = true;
      wasConnected = true;
      lostSince = 0;
      lastAttempt = 0;
      Serial.printf("Wi-Fi reconnected: http://%s  (or http://%s.local)\n",
                    WiFi.localIP().toString().c_str(), kHostname);
      MDNS.begin(kHostname);
      MDNS.addService("http", "tcp", 80);
      stopAp();
    }
  } else {
    if (wasConnected) {
      wasConnected = false;
      staConnected = false;
      lostSince = now;
      lastAttempt = now;
      Serial.println("Wi-Fi disconnected. Watchdog monitoring connection...");
    }

    if (lostSince == 0) {
      lostSince = now;
      lastAttempt = now;
    }

    const uint32_t elapsed = (uint32_t)(now - lostSince);

    // If disconnected for longer than fallback grace period, enable emergency AP
    if (elapsed >= kWifiApFallbackGraceMs && !apActive) {
      Serial.println("Wi-Fi down > threshold: bringing up emergency setup AP...");
      startAp();
    }

    // Attempt periodic reconnect
    if ((uint32_t)(now - lastAttempt) >= kWifiReconnectGraceMs) {
      if (elapsed >= kWifiFullResetGraceMs) {
        Serial.printf("Wi-Fi still down (%us): performing clean reconnect to %s...\n",
                      (unsigned)(elapsed / 1000), configuredSsid.c_str());
        WiFi.disconnect();
        WiFi.setTxPower(kWifiTxPower);
        if (kWifiNarrowBandwidth) esp_wifi_set_bandwidth(WIFI_IF_STA, WIFI_BW_HT20);
        wifiBeginSta();
      } else {
        Serial.println("Wi-Fi down: triggering WiFi.reconnect()...");
        WiFi.reconnect();
      }
      lastAttempt = now;
    }
  }
}

